        <h1 class="mt-6 text-3xl font-extrabold">Aturan Komunitas</h1>
        <p>
            TitikWargi dipakai bersama oleh warga Cianjur. Supaya laporan tetap berguna dan bisa dipercaya,
            mohon ikuti aturan berikut.
        </p>

        <h2>Yang boleh dilaporkan</h2>
        <ul>
            <li>Kerusakan jalan di wilayah Cianjur: jalan berlubang, retak, amblas, atau genangan air.</li>
            <li>Kerusakan yang benar-benar ada dan Anda lihat sendiri.</li>
        </ul>

        <h2>Foto</h2>
        <ul>
            <li>Foto harus memperlihatkan kerusakan jalan yang dilaporkan.</li>
            <li>Hindari wajah orang, plat nomor kendaraan, dan nomor rumah.</li>
            <li>Jangan memakai foto hasil rekayasa atau foto dari tempat lain.</li>
        </ul>

        <h2>Lokasi dan keterangan</h2>
        <ul>
            <li>Letakkan pin tepat di titik kerusakan.</li>
            <li>Pilih tingkat keparahan dengan jujur.</li>
            <li>Tulis keterangan yang sopan dan membantu. Jangan menulis data pribadi orang lain.</li>
        </ul>

        <h2>Yang tidak boleh</h2>
        <ul>
            <li>Spam, iklan, atau laporan palsu.</li>
            <li>
                Kampanye politik atau promosi partai dan calon mana pun. TitikWargi independen dan tidak
                terafiliasi dengan pemerintah atau partai mana pun.
            </li>
            <li>Ujaran kebencian, hinaan, atau konten yang menyinggung suku, agama, ras, dan antargolongan (SARA).</li>
            <li>Menyalahgunakan tombol "Saya juga terdampak" atau "Laporkan konten ini".</li>
        </ul>

        <h2>Batas pemakaian</h2>
        <p>Setiap akun dapat membuat maksimal 5 laporan per hari.</p>

        <h2>Jika ada pelanggaran</h2>
        <ul>
            <li>Warga dapat menekan <strong>"Laporkan konten ini"</strong> di halaman laporan.</li>
            <li>Moderator akan memeriksa laporan tersebut, lalu dapat menyembunyikan laporan, memberi peringatan, atau memblokir akun selama 7 hari, 30 hari, atau permanen.</li>
            <li>Akun yang diblokir tidak dapat membuat laporan baru.</li>
            <li>Setiap tindakan moderator dicatat beserta alasannya.</li>
        </ul>

