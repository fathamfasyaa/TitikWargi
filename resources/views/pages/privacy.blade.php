        <h1 class="mt-6 text-3xl font-extrabold">Kebijakan Privasi</h1>
        <p>
            TitikWargi adalah platform warga Cianjur untuk melaporkan jalan rusak. TitikWargi dibuat oleh
            warga bersama Velvorfa, dan tidak terafiliasi dengan pemerintah atau partai mana pun.
            Halaman ini menjelaskan data apa yang kami simpan, untuk apa, dan siapa yang bisa melihatnya.
        </p>

        <h2>Data yang kami simpan</h2>
        <p><strong>Saat Anda masuk dengan Google:</strong></p>
        <ul>
            <li>Nama, alamat email, dan foto profil akun Google Anda.</li>
            <li>Nomor ID akun Google, supaya kami mengenali Anda saat masuk lagi.</li>
        </ul>
        <p>Kami tidak pernah menerima atau menyimpan kata sandi Google Anda.</p>

        <p><strong>Saat Anda membuat laporan:</strong></p>
        <ul>
            <li>Foto kerusakan jalan (maksimal 3).</li>
            <li>Titik lokasi yang Anda pilih di peta.</li>
            <li>Jenis kerusakan, tingkat keparahan, alamat atau patokan, dan keterangan yang Anda tulis.</li>
            <li>Waktu laporan dibuat.</li>
        </ul>

        <p><strong>Saat Anda memakai tombol lain:</strong></p>
        <ul>
            <li>Tombol "Saya juga terdampak": catatan bahwa akun Anda mendukung laporan tersebut.</li>
            <li>Tombol "Laporkan konten ini": alasan dan catatan yang Anda kirim ke moderator.</li>
        </ul>

        <p><strong>Data teknis:</strong></p>
        <ul>
            <li>Cookie sesi, supaya Anda tetap masuk. Kami tidak memakai cookie iklan atau pelacak.</li>
            <li>Alamat IP dan jenis browser, yang tersimpan bersama sesi login dan dipakai untuk membatasi penyalahgunaan (misalnya terlalu banyak kiriman).</li>
        </ul>

        <h2>Foto dan lokasi</h2>
        <ul>
            <li>
                Foto dari HP biasanya berisi data tersembunyi (EXIF), seperti posisi GPS tempat foto diambil
                dan merek HP. <strong>Semua data tersembunyi ini kami hapus</strong> sebelum foto disimpan.
                Foto juga diperkecil.
            </li>
            <li>
                GPS HP hanya dipakai di browser Anda untuk meletakkan pin di peta. Yang kami simpan hanya titik
                akhir yang Anda kirim, bukan riwayat lokasi Anda.
            </li>
            <li>
                Mohon tidak memotret wajah orang, plat nomor kendaraan, atau nomor rumah.
            </li>
        </ul>

        <h2>Apa yang bisa dilihat orang lain</h2>
        <ul>
            <li>
                <strong>Publik (siapa saja, tanpa login):</strong> foto, lokasi, jenis kerusakan, tingkat keparahan,
                alamat atau patokan, keterangan, waktu laporan, dan jumlah warga yang mendukung.
            </li>
            <li>
                <strong>Tidak ditampilkan ke publik:</strong> nama, email, dan foto profil pelapor, serta siapa saja
                yang mendukung atau melaporkan sebuah laporan.
            </li>
            <li>
                <strong>Moderator (admin TitikWargi):</strong> dapat melihat nama dan email pelapor, serta siapa yang
                mengirim "Laporkan konten ini", untuk menangani pelanggaran Aturan Komunitas.
            </li>
        </ul>

        <h2>Layanan pihak lain</h2>
        <ul>
            <li><strong>Google</strong>: untuk proses masuk (login).</li>
            <li>
                <strong>OpenStreetMap</strong>: gambar peta dimuat langsung dari server OpenStreetMap, sehingga
                server mereka menerima alamat IP Anda saat peta ditampilkan.
            </li>
            <li>
                <strong>WhatsApp</strong>: hanya jika Anda menekan tombol "Bagikan ke WA".
            </li>
        </ul>
        <p>Kami tidak memakai iklan, tidak memakai alat analitik pihak ketiga, dan tidak menjual data Anda.</p>

